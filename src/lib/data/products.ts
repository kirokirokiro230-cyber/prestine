/**
 * The exported catalogue.
 *
 * `rating` is computed from the same seeded roll the product page uses to build
 * the review list, so a card's star average can never contradict the reviews
 * shown on the page. Critically, only the *statistics* module is imported here —
 * the review prose stays out of the catalogue, and therefore out of every listing
 * page's payload.
 */
export const products: Product[] = [...seeds, ...seedsContinued].map(
  ({ reviewSeed, ...product }) => ({
    ...product,
    reviewCount: reviewSeed,
    rating: averageOf(rollReviews(product.slug, reviewSeed)),
  }),
);

export default products;
